"""Write schema.sql (reference DDL for DBAs). The app itself creates tables from app/models.py."""
from sqlalchemy.dialects import mysql
from sqlalchemy.schema import CreateTable

from app import models  # noqa: F401
from app.db import Base

with open("schema.sql", "w", encoding="utf-8") as f:
    f.write("-- Generated by export_schema.py from app/models.py (MySQL dialect)\n")
    f.write("CREATE DATABASE IF NOT EXISTS innovation_hub CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;\n")
    f.write("USE innovation_hub;\n\n")
    for table in Base.metadata.sorted_tables:
        f.write(str(CreateTable(table).compile(dialect=mysql.dialect())).strip() + ";\n\n")
print("schema.sql written")
